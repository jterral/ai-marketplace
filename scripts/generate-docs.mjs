#!/usr/bin/env node
// Regenerates the plugin catalog in README.md from marketplace.json, the plugin
// directories and the SKILL.md / command / agent frontmatter.
//
// Usage:
//   node scripts/generate-docs.mjs          rewrite the generated section
//   node scripts/generate-docs.mjs --check  fail if the section is out of date (CI)

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadCatalog, root } from "./lib.mjs";

const BEGIN = "<!-- BEGIN:plugins (generated by scripts/generate-docs.mjs, do not edit) -->";
const END = "<!-- END:plugins -->";

const cell = (text) => text.replace(/\|/g, "\\|");
const firstSentence = (text) => {
  const match = text.match(/^(.+?[.!?])(\s|$)/);
  return (match ? match[1] : text).replace(/\.$/, "");
};

function render({ marketplaceName, plugins }) {
  const out = [];
  out.push("```txt", `/plugin marketplace add jterral/${marketplaceName}`, "```", "");
  for (const plugin of plugins) {
    out.push(`### ${plugin.name}`, "", plugin.description, "");
    out.push("```txt", `/plugin install ${plugin.name}@${marketplaceName}`, "```", "");
    out.push("| Component | Type | Description |", "| --------- | ---- | ----------- |");
    for (const c of plugin.commands) out.push(`| \`/${c.name}\` | command | ${cell(firstSentence(c.description))} |`);
    for (const a of plugin.agents) out.push(`| \`${a.name}\` | agent | ${cell(firstSentence(a.description))} |`);
    for (const s of plugin.skills) {
      const link = `[${s.name}](./${plugin.source.replace(/^\.\//, "")}/skills/${s.name}/SKILL.md)`;
      out.push(`| ${link} | skill | ${cell(firstSentence(s.description))} |`);
    }
    out.push("");
  }
  out.push("Once installed, skills are namespaced by plugin (e.g. `git-workflow:git-conventional-commit`, `code-auditor:auditor`).");
  return out.join("\n");
}

const readme = join(root, "README.md");
const current = readFileSync(readme, "utf8");
const start = current.indexOf(BEGIN);
const end = current.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error(`README.md must contain the markers:\n  ${BEGIN}\n  ${END}`);
  process.exit(1);
}

const next = `${current.slice(0, start)}${BEGIN}\n\n${render(loadCatalog())}\n\n${current.slice(end)}`;

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("README.md plugin catalog is out of date. Run: node scripts/generate-docs.mjs");
    process.exit(1);
  }
  console.log("README.md plugin catalog is up to date.");
} else {
  writeFileSync(readme, next);
  console.log(next === current ? "README.md already up to date." : "README.md updated.");
}
